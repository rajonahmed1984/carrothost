<?php

namespace Tests\Feature;

use App\Mail\AdminNotice;
use App\Models\Client;
use App\Models\Product;
use App\Models\ProductGroup;
use App\Models\User;
use App\Services\BillingService;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Mail;
use Illuminate\Support\Facades\Queue;
use Tests\TestCase;

class AdminNotificationsTest extends TestCase
{
    use RefreshDatabase;

    private Client $client;

    private Product $product;

    protected function setUp(): void
    {
        parent::setUp();
        Mail::fake();
        Queue::fake();
        $admin = User::factory()->create(['email' => 'boss@example.com']);
        $admin->forceFill(['is_admin' => true])->save();

        $group = ProductGroup::create(['name' => 'Hosting', 'slug' => 'hosting', 'is_visible' => true]);
        $this->product = Product::create(['name' => 'Starter', 'type' => 'shared_hosting', 'module' => null, 'product_group_id' => $group->id, 'is_active' => true, 'setup_mode' => 'accept']);
        $this->product->prices()->create(['cycle' => 'monthly', 'price' => '300.00']);
        $this->client = Client::create(['name' => 'Insight Dhaka', 'email' => 'buyer@example.com', 'password' => 'secret-pass-1', 'phone' => '01700000000', 'address' => 'Mirpur', 'city' => 'Dhaka']);
    }

    public function test_a_new_order_emails_the_admins_with_the_order_customer_and_ip(): void
    {
        $this->actingAs($this->client, 'client')
            ->postJson('/api/client/orders', ['product_id' => $this->product->id, 'cycle' => 'monthly', 'domain' => 'shop.com'], ['REMOTE_ADDR' => '10.0.0.7'])
            ->assertCreated();

        Mail::assertQueued(AdminNotice::class, function (AdminNotice $mail) {
            $html = $mail->render();

            return $mail->hasTo('boss@example.com') && str_starts_with($mail->subjectLine, 'New order #')
                && str_contains($html, 'Insight Dhaka') && str_contains($html, '01700000000') && str_contains($html, '10.0.0.7')
                && str_contains($html, 'Starter (monthly) - shop.com') && str_contains($html, 'Total Due Today')
                && str_contains($html, 'automatically generated by');
        });
        // The order's invoice is part of the order email, not a second one.
        Mail::assertQueued(AdminNotice::class, 1);
        $this->assertDatabaseHas('orders', ['ip_address' => '10.0.0.7']);
    }

    public function test_invoices_raised_and_paid_email_the_admins(): void
    {
        $invoice = app(BillingService::class)->createInvoice($this->client, [['description' => 'Add Funds', 'amount' => '500.00', 'kind' => 'add_funds']], today());
        app(BillingService::class)->recordPayment($invoice, 'manual', 'TX-77', '500.00');

        Mail::assertQueued(AdminNotice::class, fn (AdminNotice $m) => $m->subjectLine === "Invoice #{$invoice->number} created - Insight Dhaka");
        Mail::assertQueued(AdminNotice::class, fn (AdminNotice $m) => str_starts_with($m->subjectLine, "Payment received for invoice #{$invoice->number}")
            && str_contains($m->render(), 'TX-77'));
    }

    public function test_each_kind_can_be_turned_off(): void
    {
        config(['billing.admin_notifications.invoice_created' => false]);
        app(BillingService::class)->createInvoice($this->client, [['description' => 'Add Funds', 'amount' => '500.00', 'kind' => 'add_funds']], today());

        Mail::assertNotQueued(AdminNotice::class);
    }

    public function test_cancelling_an_order_tells_the_admins_who_did_it(): void
    {
        $order = app(BillingService::class)->createOrder($this->client, [['product_id' => $this->product->id, 'cycle' => 'monthly', 'domain' => 'shop.com']]);
        $this->actingAs(User::where('email', 'boss@example.com')->first())->postJson("/api/orders/{$order->id}/cancel")->assertOk();

        Mail::assertQueued(AdminNotice::class, fn (AdminNotice $m) => str_contains($m->subjectLine, 'cancelled') && str_contains($m->intro, 'cancelled by'));
    }

    public function test_a_new_ticket_emails_the_admins(): void
    {
        app(\App\Services\TicketService::class)->open($this->client, ['department' => 'support', 'subject' => 'Help with email', 'message' => 'Hi']);

        Mail::assertQueued(AdminNotice::class, 1);
        Mail::assertQueued(AdminNotice::class, fn (AdminNotice $m) => str_starts_with($m->subjectLine, 'New ticket #'));
    }
}
